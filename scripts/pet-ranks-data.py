#!/usr/bin/env python3
"""Write addons/ForeverGuide/PetRanks.lua: every hunter pet ability with
its ranks, each rank as the spell the hunter knows (Beast Training) and the
spell the pet casts.

    pet-ranks-data.py [table dir]   default scratchpad/foreverguide/tables

The directory holds the client's SkillLineAbility.csv, SpellEffect.csv,
SpellName.csv and Spell.csv for the installed build:
https://wago.tools/db2/<Table>/csv?build=<version>

A guide's ".train <id>" line for a pet ability names either spell, and a
hunter who can already teach a higher rank has no use for the lower one.
ForeverGuide's State.KnowsSpell uses this table to count such a line done.

Source: skill line 261 (Beast Training) lists the hunter's spells; each has
one effect 36 (learn spell) whose trigger spell is the pet's. Ranks are
grouped by the spell's name and ordered by the number in its subtext
("Rank 3"). SkillLineAbility.SupercedesSpell is not used for the order
because it has gaps (Charge rank 6 and Harass ranks 2 and 3 name no
predecessor in build 1.60.1.70938); where it disagrees with the order by
rank the script says so.
"""
import csv
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "addons" / "ForeverGuide" / "PetRanks.lua"

BEAST_TRAINING = "261"
LEARN_SPELL = "36"


def rows(path):
    with open(path, newline="", encoding="utf-8") as handle:
        return list(csv.DictReader(handle))


def main():
    tables = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "scratchpad/foreverguide/tables"
    abilities = rows(tables / "SkillLineAbility.csv")
    names = {row["ID"]: row["Name_lang"] for row in rows(tables / "SpellName.csv")}
    subtext = {row["ID"]: row["NameSubtext_lang"] for row in rows(tables / "Spell.csv")}

    hunter = {row["Spell"] for row in abilities if row["SkillLine"] == BEAST_TRAINING}
    teaches = {}
    for row in rows(tables / "SpellEffect.csv"):
        if row["Effect"] == LEARN_SPELL and row["SpellID"] in hunter:
            if row["SpellID"] in teaches:
                sys.exit(f"spell {row['SpellID']} teaches more than one spell")
            teaches[row["SpellID"]] = row["EffectTriggerSpell"]

    previous = {row["Spell"]: row["SupercedesSpell"] for row in abilities if row["SupercedesSpell"] != "0"}

    chains = {}
    for teach, pet in teaches.items():
        match = re.search(r"\d+", subtext.get(pet, ""))
        if not match:
            sys.exit(f"pet spell {pet} ({names.get(pet)}) has no rank in its subtext")
        chains.setdefault(names[pet], []).append((int(match.group()), int(teach), int(pet)))

    lines = [
        "-- Generated by scripts/pet-ranks-data.py from the client's SkillLineAbility,",
        "-- SpellEffect, SpellName and Spell tables. Do not edit: run the script again.",
        "-- One line per hunter pet ability, ranks in order; each rank is",
        "-- { the spell the hunter knows (Beast Training), the spell the pet casts }.",
        "local _, ns = ...",
        "",
        "ns.PET_RANKS = {",
    ]
    for name in sorted(chains):
        ranks = sorted(chains[name])
        numbers = [rank for rank, _, _ in ranks]
        if numbers != list(range(1, len(ranks) + 1)):
            sys.exit(f"{name}: ranks {numbers} are not 1..{len(ranks)}")
        for (_, _, lower), (rank, _, pet) in zip(ranks, ranks[1:]):
            if previous.get(str(pet)) != str(lower):
                print(f"note: {name} rank {rank} ({pet}) supersedes {previous.get(str(pet))} in the table, not {lower}")
        cells = ", ".join(f"{{ {teach}, {pet} }}" for _, teach, pet in ranks)
        lines.append(f"    {{ {cells} }}, -- {name}")
    lines.append("}")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{OUT.relative_to(ROOT)}: {len(chains)} abilities, {len(teaches)} ranks")


if __name__ == "__main__":
    main()
