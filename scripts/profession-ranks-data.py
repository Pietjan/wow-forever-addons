#!/usr/bin/env python3
"""Write addons/ForeverGuide/ProfessionRanks.lua: every profession's rank
spells (Apprentice, Journeyman, Expert, Artisan), in order.

    profession-ranks-data.py [table dir]   default scratchpad/foreverguide/tables

The directory holds the client's SkillLine.csv, SkillLineAbility.csv,
SpellName.csv and Spell.csv for the installed build:
https://wago.tools/db2/<Table>/csv?build=<version>

Training a higher rank replaces the lower one: with Journeyman Cooking
(3102) learned, IsPlayerSpell(2550) (Apprentice) is false (seen in game
2026-11-20). A guide's ".train 2550" would then never be done.
ForeverGuide's State.KnowsSpell uses this table to count such a line done
when a rank as high or higher is known.

Source: skill lines with SkillLine.CategoryID 9 or 11 (secondary and
primary professions); the spells on them whose Spell.NameSubtext_lang is
one of the four rank words, grouped by skill line and spell name. A line
can hold more than one spell per rank (Cooking has 2550 and 1240945 as
Apprentice); each rank lists them all. SkillLineAbility.SupercedesSpell is
not used because it has gaps (Expert Mining 3564 and Expert Herbalism 3570
name no predecessor in build 1.60.1.70959).
"""
import csv
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "addons" / "ForeverGuide" / "ProfessionRanks.lua"

PROFESSION_CATEGORIES = {"9", "11"}
RANKS = ["Apprentice", "Journeyman", "Expert", "Artisan"]


def rows(path):
    if not path.exists():
        sys.exit(f"{path}: not found; fetch https://wago.tools/db2/{path.stem}/csv?build=<version>")
    with open(path, newline="", encoding="utf-8") as handle:
        return list(csv.DictReader(handle))


def main():
    tables = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "scratchpad/foreverguide/tables"
    lines_ = {row["ID"]: row["DisplayName_lang"] for row in rows(tables / "SkillLine.csv")
              if row["CategoryID"] in PROFESSION_CATEGORIES}
    names = {row["ID"]: row["Name_lang"] for row in rows(tables / "SpellName.csv")}
    subtext = {row["ID"]: row["NameSubtext_lang"].strip() for row in rows(tables / "Spell.csv")}

    groups = {}
    for row in rows(tables / "SkillLineAbility.csv"):
        spell = row["Spell"]
        if row["SkillLine"] not in lines_ or subtext.get(spell) not in RANKS:
            continue
        key = (lines_[row["SkillLine"]], row["SkillLine"], names.get(spell, "?"))
        ranks = groups.setdefault(key, [[] for _ in RANKS])
        if int(spell) not in ranks[RANKS.index(subtext[spell])]:
            ranks[RANKS.index(subtext[spell])].append(int(spell))

    out = [
        "-- Generated by scripts/profession-ranks-data.py from the client's SkillLine,",
        "-- SkillLineAbility, SpellName and Spell tables. Do not edit: run the script again.",
        "-- One line per profession, ranks in order (Apprentice, Journeyman, Expert,",
        "-- Artisan); each rank lists the spells that stand for it.",
        "local _, ns = ...",
        "",
        "ns.PROFESSION_RANKS = {",
    ]
    count = 0
    for key in sorted(groups):
        ranks = [sorted(spells) for spells in groups[key]]
        if sum(1 for spells in ranks if spells) < 2:
            continue  # a single rank has nothing to cover it
        if not all(ranks):
            missing = [RANKS[i] for i, spells in enumerate(ranks) if not spells]
            print(f"note: {key[2]} on skill line {key[1]} has no {', '.join(missing)}")
        cells = ", ".join("{ " + ", ".join(map(str, spells)) + " }" for spells in ranks)
        out.append(f"    {{ {cells} }}, -- {key[2]} ({key[1]})")
        count += 1
    out.append("}")
    OUT.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"{OUT.relative_to(ROOT)}: {count} professions")


if __name__ == "__main__":
    main()
