#!/usr/bin/env python3
"""Write addons/SellAdvice/Data.lua: what disenchanting an item gives.

    sell-advice-data.py [guide dir]     default ~/src/github.com/pietjan/wow-profession-guide

Sources, all from the profession guide's folder:
- disenchant.txt: what comes out of each bracket (Classic's rates; the
  server decides them, the client does not say).
- cache/<newest build>/ItemDisenchantLoot.csv: the game's brackets, so a
  bracket the game does not have is left out.
- cache/<newest build>/ItemSparse.csv: material names to item IDs, and the
  items flagged as not disenchantable.
"""
import csv
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "addons" / "SellAdvice" / "Data.lua"
NO_DISENCHANT = 0x8000
QUALITY = {"uncommon": 2, "rare": 3, "epic": 4}
KIND = {"weapon": [2], "armor": [4], "any": [2, 4]}


def rows(path):
    with open(path, newline="", encoding="utf-8") as handle:
        return list(csv.DictReader(handle))


def build_key(name):
    return tuple(int(part) for part in name.split("."))


def main():
    guide = Path(sys.argv[1]) if len(sys.argv) > 1 else Path.home() / "src/github.com/pietjan/wow-profession-guide"
    builds = sorted((d for d in (guide / "cache").iterdir() if (d / "ItemSparse.csv").exists()), key=lambda d: build_key(d.name))
    if not builds:
        sys.exit(f"no cached client tables under {guide / 'cache'}")
    cache = builds[-1]

    sparse = rows(cache / "ItemSparse.csv")
    by_name = {row["Display_lang"].lower(): int(row["ID"]) for row in sparse}
    kinds = {int(r["ID"]): int(r["ClassID"]) for r in rows(cache / "Item.csv")}
    no_de = sorted(
        int(row["ID"]) for row in sparse
        if int(row["Flags_0"]) & NO_DISENCHANT
        and int(row["OverallQualityID"]) in (2, 3, 4)
        and kinds.get(int(row["ID"])) in (2, 4)
    )
    brackets = {
        (int(r["Class"]), int(r["Quality"]), int(r["MinLevel"]), int(r["MaxLevel"]))
        for r in rows(cache / "ItemDisenchantLoot.csv")
    }

    table = []  # (class, quality, low, high, [(item id, average amount)])
    materials = set()
    for number, line in enumerate((guide / "disenchant.txt").read_text().splitlines(), 1):
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        head = re.fullmatch(r"(\w+) (\w+) (\d+)-(\d+): (.+)", line)
        parts = re.findall(r"(\d+(?:\.\d+)?)% (\d+)(?:-(\d+))? ([^,]+)", head[5]) if head else []
        if not parts or head[1] not in QUALITY or head[2] not in KIND:
            sys.exit(f"disenchant.txt:{number}: cannot read this line")
        gives = []
        for chance, low, high, name in parts:
            item = by_name.get(name.strip().lower())
            if not item:
                sys.exit(f"disenchant.txt:{number}: the game has no item called '{name.strip()}'")
            gives.append((item, float(chance) / 100 * (int(low) + int(high or low)) / 2))
            materials.add(name.strip())
        quality, low, high = QUALITY[head[1]], int(head[3]), int(head[4])
        for kind in KIND[head[2]]:
            # Keep only the part of the line the game has brackets for.
            for b_kind, b_quality, b_low, b_high in sorted(brackets):
                if b_kind == kind and b_quality == quality and b_low <= high and b_high >= low:
                    table.append((kind, quality, max(low, b_low), min(high, b_high), gives))

    # Three lesser essences make one greater and back, so each is worth
    # the better of its own price and the other's.
    pairs = []
    for name in sorted(materials):
        if name.startswith("Lesser "):
            greater = "Greater " + name[len("Lesser "):]
            if greater.lower() in by_name:
                pairs.append((by_name[name.lower()], by_name[greater.lower()]))

    out = [
        "-- Generated by scripts/sell-advice-data.py from the profession guide's",
        f"-- disenchant.txt and the client tables of build {cache.name}. Do not edit.",
        "local _, ns = ...",
        "",
        "-- { class, quality, lowest item level, highest, { item ID, average amount, ... } }",
        "ns.disenchant = {",
    ]
    for kind, quality, low, high, gives in sorted(table, key=lambda t: t[:4]):
        flat = ", ".join(f"{item}, {amount:g}" for item, amount in gives)
        out.append(f"\t{{ {kind}, {quality}, {low}, {high}, {{ {flat} }} }},")
    out += ["}", "", "-- lesser essence -> greater essence (3 lesser = 1 greater)", "ns.essences = {"]
    out += [f"\t[{lesser}] = {greater}," for lesser, greater in pairs]
    out += ["}", "", "-- Weapons and armour of uncommon or better that cannot be disenchanted.", "ns.noDisenchant = {"]
    for i in range(0, len(no_de), 10):
        out.append("\t" + " ".join(f"[{item}] = true," for item in no_de[i:i + 10]))
    out += ["}", ""]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(out))
    print(f"{OUT}: {len(table)} brackets, {len(pairs)} essence pairs, {len(no_de)} items that do not disenchant")


if __name__ == "__main__":
    main()
