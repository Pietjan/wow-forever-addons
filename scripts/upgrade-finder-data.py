#!/usr/bin/env python3
"""Write addons/UpgradeFinder/Data.lua: the gear that professions make.

    upgrade-finder-data.py [guide dir]     default ~/src/github.com/pietjan/wow-profession-guide

Sources, all client tables from the profession guide's cache/<newest build>/:
- SkillLine.csv: the professions (category 11) and their names.
- SkillLineAbility.csv: each profession's recipes. The skill a recipe
  needs is not in the client (MinSkillLineRank is 1 throughout).
- SpellEffect.csv: what a recipe makes (effect 24, create item).
- Item.csv: which of those items are weapons or armor. An item the table
  does not have is kept: half of the game's gear reaches the client as a
  hotfix and is in none of these files.

Where other items come from (quests, drops, vendors) is not in the client;
the addon reads that from QuestieDB while the game runs.
"""
import csv
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "addons" / "UpgradeFinder" / "Data.lua"
PROFESSIONS = 11  # SkillLine.CategoryID
CREATE_ITEM = "24"  # SpellEffect.Effect
GEAR = ("2", "4")  # Item.ClassID: weapon, armor


def rows(path):
    with open(path, newline="", encoding="utf-8") as handle:
        return list(csv.DictReader(handle))


def build_key(name):
    return tuple(int(part) for part in name.split("."))


def main():
    guide = Path(sys.argv[1]) if len(sys.argv) > 1 else Path.home() / "src/github.com/pietjan/wow-profession-guide"
    needed = ("SkillLine.csv", "SkillLineAbility.csv", "SpellEffect.csv", "Item.csv")
    builds = sorted(
        (d for d in (guide / "cache").iterdir() if all((d / name).exists() for name in needed)),
        key=lambda d: build_key(d.name),
    )
    if not builds:
        sys.exit(f"no cached client tables under {guide / 'cache'}")
    cache = builds[-1]

    # A profession's recipes hang on the profession itself or on a child
    # line of the same name; both count as the parent.
    lines = {int(r["ID"]): r for r in rows(cache / "SkillLine.csv")}
    profession = {}
    for line_id, row in lines.items():
        if int(row["CategoryID"]) != PROFESSIONS:
            continue
        parent = int(row["ParentSkillLineID"])
        profession[line_id] = parent if parent in lines else line_id
    names = {top: lines[top]["DisplayName_lang"] for top in set(profession.values())}

    recipes = {}  # spell -> profession
    for row in rows(cache / "SkillLineAbility.csv"):
        line = int(row["SkillLine"])
        if line in profession:
            recipes[row["Spell"]] = profession[line]

    kinds = {r["ID"]: r["ClassID"] for r in rows(cache / "Item.csv")}
    crafted = {}  # item -> profession
    for row in rows(cache / "SpellEffect.csv"):
        item = row["EffectItemType"]
        if row["Effect"] != CREATE_ITEM or row["SpellID"] not in recipes or item in ("", "0"):
            continue
        if kinds.get(item, GEAR[0]) not in GEAR:
            continue
        crafted.setdefault(int(item), recipes[row["SpellID"]])

    used = sorted(set(crafted.values()))
    out = [
        "-- Generated by scripts/upgrade-finder-data.py from the client tables of",
        f"-- build {cache.name}. Do not edit.",
        "local _, ns = ...",
        "",
        "-- Profession skill line -> name.",
        "ns.professions = {",
    ]
    out += [f'\t[{line}] = "{names[line]}",' for line in used]
    out += ["}", "", "-- Gear a profession makes: item ID -> skill line.", "ns.crafted = {"]
    out += [f"\t[{item}] = {line}," for item, line in sorted(crafted.items())]
    out += ["}", ""]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(out), encoding="utf-8")
    print(f"{OUT.relative_to(ROOT)}: {len(crafted)} crafted items from {len(used)} professions, build {cache.name}")


if __name__ == "__main__":
    main()
