#!/usr/bin/env python3
"""Write addons/CraftProfit/Data.lua: which item teaches a recipe, and the skill it needs.

    craft-profit-data.py [guide dir]     default ~/src/github.com/pietjan/wow-profession-guide

Sources, all client tables from the profession guide's cache/<newest build>/:
- ItemEffect.csv: an item's spells; trigger 6 is "learn this spell", the
  recipe the pattern teaches (a recipe's ID in the profession window is
  its spell ID).
- ItemXItemEffect.csv: which item an ItemEffect row belongs to.
- ItemSparse.csv: the pattern's RequiredSkillRank, the skill it needs.
- SkillLine.csv, SkillLineAbility.csv: which spells are profession recipes
  (category 11), so class books and the like are left out.

What a trainer wants for a recipe is not in the client; the addon reads it
at the trainer. Patterns that reach the client only as a hotfix are in none
of these files and are missing here.
"""
import csv
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "addons" / "CraftProfit" / "Data.lua"
LEARN_SPELL = "6"  # ItemEffect.TriggerType
PROFESSIONS = "11"  # SkillLine.CategoryID


def rows(path):
    with open(path, newline="", encoding="utf-8") as handle:
        return list(csv.DictReader(handle))


def build_key(name):
    return tuple(int(part) for part in name.split("."))


def main():
    guide = Path(sys.argv[1]) if len(sys.argv) > 1 else Path.home() / "src/github.com/pietjan/wow-profession-guide"
    needed = ("ItemEffect.csv", "ItemXItemEffect.csv", "ItemSparse.csv", "SkillLine.csv", "SkillLineAbility.csv")
    builds = sorted(
        (d for d in (guide / "cache").iterdir() if all((d / name).exists() for name in needed)),
        key=lambda d: build_key(d.name),
    )
    if not builds:
        sys.exit(f"no cached client tables under {guide / 'cache'}")
    cache = builds[-1]

    lines = {r["ID"] for r in rows(cache / "SkillLine.csv") if r["CategoryID"] == PROFESSIONS}
    recipes = {int(r["Spell"]) for r in rows(cache / "SkillLineAbility.csv") if r["SkillLine"] in lines}
    item_of = {r["ItemEffectID"]: r["ItemID"] for r in rows(cache / "ItemXItemEffect.csv")}
    skill = {r["ID"]: int(r["RequiredSkillRank"] or 0) for r in rows(cache / "ItemSparse.csv")}
    teaches = {}  # spell -> {item: skill}
    for row in rows(cache / "ItemEffect.csv"):
        item = item_of.get(row["ID"])
        if row["TriggerType"] != LEARN_SPELL or not item or item not in skill:
            continue
        spell = int(row["SpellID"])
        if spell in recipes:
            teaches.setdefault(spell, {})[int(item)] = skill[item]

    out = [
        "-- Generated by scripts/craft-profit-data.py from the client tables of",
        f"-- build {cache.name}. Do not edit.",
        "local _, ns = ...",
        "",
        "-- Recipe (spell ID) -> { pattern item ID, skill it needs, ... }",
        "ns.patterns = {",
    ]
    for spell, items in sorted(teaches.items()):
        pairs = ", ".join(f"{item}, {need}" for item, need in sorted(items.items()))
        out.append(f"\t[{spell}] = {{ {pairs} }},")
    out += ["}", ""]
    OUT.write_text("\n".join(out), encoding="utf-8")
    print(f"{OUT.relative_to(ROOT)}: {len(teaches)} recipes taught by an item, build {cache.name}")


if __name__ == "__main__":
    main()
